#![allow(dead_code)]
//! Shared test helpers: a config builder, a fake model server, a tiny HTTP client.

use arrowbridge_companion::config::Config;
use arrowbridge_companion::http;
use arrowbridge_companion::server::{self, RunningServer, Shared};
use serde_json::{Value, json};
use std::collections::HashMap;
use std::io::{Read, Write};
use std::net::{SocketAddr, TcpListener, TcpStream};
use std::sync::{Arc, Mutex};
use std::time::Duration;

pub fn config(vars: &[(&str, &str)]) -> Config {
    let map: HashMap<String, String> = vars.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect();
    Config::from_lookup(&|k| map.get(k).cloned()).expect("test config")
}

pub fn start_server(cfg: Config) -> (Arc<Shared>, RunningServer) {
    let listener = server::bind_listener(SocketAddr::new(cfg.bind, 0), true).unwrap();
    let port = listener.local_addr().unwrap().port();
    let shared = Arc::new(Shared::new(cfg, port));
    let running = server::start(shared.clone(), listener);
    (shared, running)
}

pub fn request(addr: SocketAddr, method: &str, path: &str, headers: &[(&str, &str)], body: Option<&[u8]>) -> (u16, String, Vec<u8>) {
    let mut s = TcpStream::connect(addr).unwrap();
    s.set_read_timeout(Some(Duration::from_secs(10))).unwrap();
    let mut head = format!("{method} {path} HTTP/1.1\r\nHost: {addr}\r\n");
    for (k, v) in headers {
        head.push_str(&format!("{k}: {v}\r\n"));
    }
    if let Some(b) = body {
        head.push_str(&format!("Content-Type: application/json\r\nContent-Length: {}\r\n", b.len()));
    }
    head.push_str("\r\n");
    s.write_all(head.as_bytes()).unwrap();
    if let Some(b) = body {
        s.write_all(b).unwrap();
    }
    read_response(&mut s)
}

pub fn raw(addr: SocketAddr, bytes: &[u8]) -> (u16, String, Vec<u8>) {
    let mut s = TcpStream::connect(addr).unwrap();
    s.set_read_timeout(Some(Duration::from_secs(10))).unwrap();
    s.write_all(bytes).unwrap();
    read_response(&mut s)
}

fn read_response(s: &mut TcpStream) -> (u16, String, Vec<u8>) {
    let mut buf = Vec::new();
    s.read_to_end(&mut buf).unwrap();
    let split = http::find_subslice(&buf, b"\r\n\r\n").expect("response head");
    let head = String::from_utf8_lossy(&buf[..split]).into_owned();
    let status: u16 = head.split_whitespace().nth(1).unwrap().parse().unwrap();
    let ct = head
        .lines()
        .find_map(|l| l.to_ascii_lowercase().strip_prefix("content-type:").map(|v| v.trim().to_string()))
        .unwrap_or_default();
    (status, ct, buf[split + 4..].to_vec())
}

pub fn post_json(addr: SocketAddr, path: &str, headers: &[(&str, &str)], v: &Value) -> (u16, Value) {
    // Owner POSTs need the custom header (C2); sending it on every test POST is harmless.
    let mut h: Vec<(&str, &str)> = headers.to_vec();
    h.push(("X-ArrowBridge-Owner", "1"));
    let (st, _, body) = request(addr, "POST", path, &h, Some(v.to_string().as_bytes()));
    (st, serde_json::from_slice(&body).unwrap_or(Value::Null))
}

pub fn get_json(addr: SocketAddr, path: &str, headers: &[(&str, &str)]) -> (u16, Value) {
    let (st, _, body) = request(addr, "GET", path, headers, None);
    (st, serde_json::from_slice(&body).unwrap_or(Value::Null))
}

#[derive(Clone, Debug)]
pub struct Seen {
    pub path: String,
    pub body: Value,
    pub auth: Option<String>,
}

pub struct FakeUpstream {
    pub port: u16,
    pub seen: Arc<Mutex<Vec<Seen>>>,
}

/// A stand-in for llama.cpp with the same canned replies the Python fixtures were recorded
/// against (see tests/fixtures, generated by running the Python companion).
pub fn fake_upstream() -> FakeUpstream {
    let l = TcpListener::bind("127.0.0.1:0").unwrap();
    let port = l.local_addr().unwrap().port();
    let seen = Arc::new(Mutex::new(Vec::new()));
    let seen2 = seen.clone();
    std::thread::spawn(move || {
        for c in l.incoming() {
            let Ok(mut s) = c else { continue };
            let Ok(req) = http::read_request(&mut s) else { continue };
            let body: Value = serde_json::from_slice(&req.body).unwrap_or(Value::Null);
            seen2.lock().unwrap().push(Seen {
                path: req.path.clone(),
                body,
                auth: req.header("Authorization").map(str::to_string),
            });
            let out = match req.path.as_str() {
                "/v1/chat/completions" => json!({"choices":[{"message":{"content":"Call 1-800-555-0100 or 911 now.  Thanks ."}}]}),
                "/v1/messages" => json!({"content":[{"type":"text","text":"Dial 613-555-0100 or 988 ok"},{"type":"tool_use"}],
                                         "stop_reason":"max_tokens","usage":{"input_tokens":3,"output_tokens":5}}),
                "/v1/messages/count_tokens" => json!({"input_tokens":7}),
                _ => {
                    let _ = http::write_response(&mut s, &http::Response::not_found());
                    continue;
                }
            };
            let _ = http::write_response(&mut s, &http::Response::json(200, &out));
        }
    });
    FakeUpstream { port, seen }
}

pub fn hex(s: &str) -> Vec<u8> {
    (0..s.len() / 2).map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap()).collect()
}

pub fn fixture(name: &str) -> Value {
    let p = format!("{}/tests/fixtures/{name}", env!("CARGO_MANIFEST_DIR"));
    serde_json::from_str(&std::fs::read_to_string(p).unwrap()).unwrap()
}

/// Like `request` but with the Host header chosen by the caller (and no default Host).
pub fn raw_host(addr: SocketAddr, method: &str, path: &str, host: &str, headers: &[(&str, &str)]) -> (u16, String, Vec<u8>) {
    let mut head = format!("{method} {path} HTTP/1.1\r\nHost: {host}\r\n");
    for (k, v) in headers {
        head.push_str(&format!("{k}: {v}\r\n"));
    }
    if method == "POST" {
        head.push_str("Content-Length: 2\r\n");
    }
    head.push_str("\r\n");
    if method == "POST" {
        head.push_str("{}");
    }
    raw(addr, head.as_bytes())
}
